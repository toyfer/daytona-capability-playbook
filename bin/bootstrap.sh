#!/usr/bin/env bash
# Scira/Daytona tool bootstrap — session-local optional tool installer.
# Usage: bash bootstrap.sh <profile> [profile...]
set -euo pipefail

TOOLS_ROOT="${TOOLS_ROOT:-/workspace/.tools}"
BIN_DIR="$TOOLS_ROOT/bin"
ENV_FILE="$TOOLS_ROOT/env"
MARKER_FILE="$TOOLS_ROOT/installed.env"
ARCH="$(uname -m)"

# Pinned static releases. Update intentionally and record in OPS.md.
JQ_URL="https://github.com/jqlang/jq/releases/download/jq-1.7.1/jq-linux-amd64"
RG_VER="14.1.1"
RG_URL="https://github.com/BurntSushi/ripgrep/releases/download/${RG_VER}/ripgrep-${RG_VER}-x86_64-unknown-linux-musl.tar.gz"
FD_VER="10.2.1"
FD_URL="https://github.com/sharkdp/fd/releases/download/v${FD_VER}/fd-v${FD_VER}-x86_64-unknown-linux-musl.tar.gz"

log()  { printf '[bootstrap] %s\n' "$*" >&2; }
die()  { printf '[bootstrap:error] %s\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

[[ "$ARCH" == "x86_64" || "$ARCH" == "amd64" ]] || die "unsupported arch: $ARCH"
mkdir -p "$BIN_DIR"
touch "$MARKER_FILE"
# shellcheck disable=SC1090
source "$MARKER_FILE" 2>/dev/null || true

write_env() {
  cat > "$ENV_FILE" <<EOS
# generated by bootstrap.sh; source in the current shell
export PATH="$BIN_DIR:\$PATH"
EOS
  export PATH="$BIN_DIR:$PATH"
}

mark() {
  local key="$1"
  if grep -q "^${key}=" "$MARKER_FILE" 2>/dev/null; then
    sed -i "s|^${key}=.*|${key}=1|" "$MARKER_FILE"
  else
    printf '%s=1\n' "$key" >> "$MARKER_FILE"
  fi
}

marked() {
  grep -q "^${1}=1$" "$MARKER_FILE" 2>/dev/null
}

apt_update_once() {
  marked APT_UPDATED && return 0
  have apt-get || die "apt-get not available"
  log "apt-get update"
  apt-get update -qq
  mark APT_UPDATED
}

apt_install() {
  apt_update_once
  log "apt-get install: $*"
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$@" </dev/null
}

download() { curl -fsSL "$1" -o "$2"; }

copy_if_present() {
  local name="$1" src
  src="$(command -v "$name" 2>/dev/null || true)"
  [[ -n "$src" ]] || return 1
  cp -f "$src" "$BIN_DIR/$name"
  chmod +x "$BIN_DIR/$name"
}

install_jq() {
  [[ -x "$BIN_DIR/jq" ]] && return 0
  if copy_if_present jq; then log "jq copied from PATH"; return 0; fi
  log "install jq (static)"
  download "$JQ_URL" "$BIN_DIR/jq"
  chmod +x "$BIN_DIR/jq"
  "$BIN_DIR/jq" --version >/dev/null
}

install_rg() {
  [[ -x "$BIN_DIR/rg" ]] && return 0
  if copy_if_present rg; then log "rg copied from PATH"; return 0; fi
  log "install rg (static musl)"
  local tmp bin
  tmp="$(mktemp -d)"
  download "$RG_URL" "$tmp/rg.tgz"
  tar -xzf "$tmp/rg.tgz" -C "$tmp"
  bin="$(find "$tmp" -type f -name rg | head -1)"
  [[ -n "$bin" ]] || die "rg binary not found"
  install -m 755 "$bin" "$BIN_DIR/rg"
  rm -rf "$tmp"
}

install_fd() {
  [[ -x "$BIN_DIR/fd" ]] && return 0
  if copy_if_present fd; then log "fd copied from PATH"; return 0; fi
  local tmp bin
  tmp="$(mktemp -d)"
  if download "$FD_URL" "$tmp/fd.tgz" 2>/dev/null; then
    tar -xzf "$tmp/fd.tgz" -C "$tmp"
    bin="$(find "$tmp" -type f -name fd | head -1)"
    if [[ -n "$bin" ]]; then
      install -m 755 "$bin" "$BIN_DIR/fd"
      rm -rf "$tmp"
      return 0
    fi
  fi
  rm -rf "$tmp"
  apt_install fd-find
  ln -sfn "$(command -v fdfind)" "$BIN_DIR/fd"
}

install_nkf() { have nkf || apt_install nkf; }
install_unzip() { have unzip || apt_install unzip; }
install_file() { have file || apt_install file; }
install_sqlite3() { have sqlite3 || apt_install sqlite3; }
install_pandoc() { have pandoc || apt_install pandoc; }
install_poppler() { have pdftotext || apt_install poppler-utils; }
install_qpdf() { have qpdf || apt_install qpdf; }
install_tesseract() { have tesseract || apt_install tesseract-ocr; }
install_tesseract_jpn() { apt_install tesseract-ocr-jpn; }
install_ffmpeg() { have ffmpeg || apt_install ffmpeg; }
install_imagemagick() { (have convert || have magick) || apt_install imagemagick; }

install_duckdb() {
  python3 -c 'import duckdb' 2>/dev/null && return 0
  if have uv; then uv pip install --system duckdb -q; else pip3 install duckdb -q; fi
  python3 -c 'import duckdb' >/dev/null
}

run_profile() {
  local profile="$1" key="PROFILE_$(tr 'a-z-' 'A-Z_' <<< "$1")"
  if marked "$key"; then
    log "profile $profile already installed"
    write_env
    return 0
  fi
  log "profile: $profile"
  case "$profile" in
    cli-min) install_jq; install_rg ;;
    cli-dev) install_jq; install_rg; install_fd; install_unzip; install_file ;;
    jp-text) install_nkf ;;
    data) install_duckdb; install_sqlite3 ;;
    docs-extra) install_pandoc; install_poppler; install_qpdf ;;
    ocr) install_tesseract; install_tesseract_jpn ;;
    media) install_ffmpeg; install_imagemagick ;;
    *) die "unknown profile: $profile" ;;
  esac
  mark "$key"
  write_env
}

usage() {
  cat <<'U'
Usage: bootstrap.sh <profile> [profile...]

Profiles:
  cli-min     jq, rg
  cli-dev     jq, rg, fd, unzip, file
  jp-text     nkf
  data        duckdb (Python), sqlite3
  docs-extra  pandoc, poppler-utils, qpdf
  ocr         tesseract, Japanese language data
  media       ffmpeg, ImageMagick

After run: source /workspace/.tools/env
U
}

main() {
  [[ $# -gt 0 ]] || { usage; return 0; }
  [[ "$1" != "-h" && "$1" != "--help" ]] || { usage; return 0; }
  [[ "${EUID:-$(id -u)}" -eq 0 ]] || log "not root: apt-backed profiles may fail"
  for profile in "$@"; do run_profile "$profile"; done
  log "OK. source $ENV_FILE"
}

main "$@"
