#!/usr/bin/env bash
# Scira/Daytona tool bootstrap — single install entrypoint.
# Usage:
#   bash bootstrap.sh cli-min
#   bash bootstrap.sh cli-min data jp-text
#   curl -fsSL "$PLAYBOOK/bin/bootstrap.sh" | bash -s -- cli-min
set -euo pipefail

TOOLS_ROOT="${TOOLS_ROOT:-/workspace/.tools}"
BIN_DIR="$TOOLS_ROOT/bin"
ENV_FILE="$TOOLS_ROOT/env"
MARKER_FILE="$TOOLS_ROOT/installed.env"
ARCH="$(uname -m)"

# Pinned release URLs (bump in OPS.md when changing)
JQ_URL="https://github.com/jqlang/jq/releases/download/jq-1.7.1/jq-linux-amd64"
RG_VER="14.1.1"
RG_URL="https://github.com/BurntSushi/ripgrep/releases/download/${RG_VER}/ripgrep-${RG_VER}-x86_64-unknown-linux-musl.tar.gz"
FD_VER="10.2.1"
FD_URL="https://github.com/sharkdp/fd/releases/download/v${FD_VER}/fd-v${FD_VER}-x86_64-unknown-linux-musl.tar.gz"

log()  { printf '[bootstrap] %s\n' "$*" >&2; }
die()  { printf '[bootstrap:error] %s\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

if [[ "$ARCH" != "x86_64" && "$ARCH" != "amd64" ]]; then
  die "unsupported arch: $ARCH (playbook pins x86_64)"
fi

mkdir -p "$BIN_DIR"
touch "$MARKER_FILE"
# shellcheck disable=SC1090
source "$MARKER_FILE" 2>/dev/null || true

ensure_path_env() {
  cat > "$ENV_FILE" <<EOS
# generated by bootstrap.sh — source this in the same shell session
export PATH="$BIN_DIR:\$PATH"
EOS
  export PATH="$BIN_DIR:$PATH"
  if [[ -w /usr/local/bin ]]; then
    for b in "$BIN_DIR"/*; do
      [[ -e "$b" ]] || continue
      [[ -f "$b" && -x "$b" ]] || continue
      base="$(basename "$b")"
      ln -sfn "$b" "/usr/local/bin/$base" 2>/dev/null || cp -f "$b" "/usr/local/bin/$base" 2>/dev/null || true
    done
  fi
}

mark() {
  local key="$1"
  if grep -q "^${key}=" "$MARKER_FILE" 2>/dev/null; then
    sed -i "s|^${key}=.*|${key}=1|" "$MARKER_FILE"
  else
    echo "${key}=1" >> "$MARKER_FILE"
  fi
  eval "${key}=1"
}

marked() {
  local key="$1"
  # shellcheck disable=SC1090
  source "$MARKER_FILE" 2>/dev/null || true
  [[ "${!key:-0}" == "1" ]]
}

apt_update_once() {
  if marked APT_UPDATED; then
    return 0
  fi
  if ! have apt-get; then
    die "apt-get not available"
  fi
  log "apt-get update"
  apt-get update -qq
  mark APT_UPDATED
}

apt_install() {
  apt_update_once
  log "apt-get install: $*"
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$@" </dev/null
}

download() {
  local url="$1" out="$2"
  if have curl; then
    curl -fsSL "$url" -o "$out"
  else
    die "curl required"
  fi
}

install_jq() {
  if [[ -x "$BIN_DIR/jq" ]] && "$BIN_DIR/jq" --version >/dev/null 2>&1; then
    log "jq already in $BIN_DIR"
    return 0
  fi
  if have jq && jq --version >/dev/null 2>&1; then
    local src
    src="$(command -v jq)"
    log "jq on PATH ($src) — copy into $BIN_DIR"
    cp -f "$src" "$BIN_DIR/jq"
    chmod +x "$BIN_DIR/jq"
    return 0
  fi
  log "install jq (static)"
  download "$JQ_URL" "$BIN_DIR/jq"
  chmod +x "$BIN_DIR/jq"
  "$BIN_DIR/jq" --version >/dev/null
}

install_rg() {
  if [[ -x "$BIN_DIR/rg" ]] && "$BIN_DIR/rg" --version >/dev/null 2>&1; then
    log "rg already in $BIN_DIR"
    return 0
  fi
  if have rg && rg --version >/dev/null 2>&1; then
    local src
    src="$(command -v rg)"
    log "rg on PATH ($src) — copy into $BIN_DIR"
    cp -f "$src" "$BIN_DIR/rg"
    chmod +x "$BIN_DIR/rg"
    return 0
  fi
  log "install rg (static musl)"
  local tmp
  tmp="$(mktemp -d)"
  download "$RG_URL" "$tmp/rg.tgz"
  tar -xzf "$tmp/rg.tgz" -C "$tmp"
  local bin
  bin="$(find "$tmp" -type f -name rg | head -1)"
  [[ -n "$bin" ]] || die "rg binary not found in archive"
  install -m 755 "$bin" "$BIN_DIR/rg"
  rm -rf "$tmp"
  "$BIN_DIR/rg" --version >/dev/null
}

install_fd() {
  if have fd && fd --version >/dev/null 2>&1; then
    log "fd already present: $(command -v fd)"
    if [[ ! -x "$BIN_DIR/fd" ]]; then
      cp -f "$(command -v fd)" "$BIN_DIR/fd" 2>/dev/null || true
      chmod +x "$BIN_DIR/fd" 2>/dev/null || true
    fi
    return 0
  fi
  log "install fd (static musl)"
  local tmp
  tmp="$(mktemp -d)"
  if download "$FD_URL" "$tmp/fd.tgz" 2>/dev/null; then
    tar -xzf "$tmp/fd.tgz" -C "$tmp"
    local bin
    bin="$(find "$tmp" -type f -name fd | head -1)"
    if [[ -n "$bin" ]]; then
      install -m 755 "$bin" "$BIN_DIR/fd"
      rm -rf "$tmp"
      "$BIN_DIR/fd" --version >/dev/null
      return 0
    fi
  fi
  rm -rf "$tmp"
  log "fd static failed; apt fd-find"
  apt_install fd-find
  if have fdfind && ! have fd; then
    ln -sfn "$(command -v fdfind)" "$BIN_DIR/fd"
  fi
}

install_nkf() {
  if have nkf; then log "nkf already present"; return 0; fi
  apt_install nkf
}

install_unzip() {
  if have unzip; then log "unzip already present"; return 0; fi
  apt_install unzip
}

install_file_bin() {
  if have file; then log "file already present"; return 0; fi
  apt_install file
}

install_sqlite3() {
  if have sqlite3; then log "sqlite3 already present"; return 0; fi
  apt_install sqlite3
}

install_duckdb_py() {
  if python3 -c "import duckdb" 2>/dev/null; then
    log "duckdb python already present"
    return 0
  fi
  log "pip/uv install duckdb"
  if have uv; then
    uv pip install --system duckdb -q
  else
    pip3 install duckdb -q
  fi
  python3 -c "import duckdb" >/dev/null
}

install_pandoc() {
  if have pandoc; then log "pandoc already present"; return 0; fi
  apt_install pandoc
}

install_poppler() {
  if have pdftotext; then log "poppler already present"; return 0; fi
  apt_install poppler-utils
}

install_qpdf() {
  if have qpdf; then log "qpdf already present"; return 0; fi
  apt_install qpdf
}

install_tesseract() {
  if have tesseract; then log "tesseract already present"; return 0; fi
  apt_install tesseract-ocr
}

install_tesseract_jpn() {
  apt_install tesseract-ocr-jpn
}

install_ffmpeg() {
  if have ffmpeg; then log "ffmpeg already present"; return 0; fi
  apt_install ffmpeg
}

install_imagemagick() {
  if have convert || have magick; then log "imagemagick already present"; return 0; fi
  apt_install imagemagick
}

install_tool() {
  case "$1" in
    jq) install_jq ;;
    rg) install_rg ;;
    fd) install_fd ;;
    nkf) install_nkf ;;
    unzip) install_unzip ;;
    file) install_file_bin ;;
    sqlite3) install_sqlite3 ;;
    duckdb-py|duckdb) install_duckdb_py ;;
    pandoc) install_pandoc ;;
    poppler-utils) install_poppler ;;
    qpdf) install_qpdf ;;
    tesseract-ocr) install_tesseract ;;
    tesseract-ocr-jpn) install_tesseract_jpn ;;
    ffmpeg) install_ffmpeg ;;
    imagemagick) install_imagemagick ;;
    *) die "unknown tool: $1" ;;
  esac
}

run_profile() {
  local profile="$1"
  local key="PROFILE_$(echo "$profile" | tr 'a-z-' 'A-Z_')"
  if marked "$key"; then
    case "$profile" in
      cli-min|cli-dev)
        if [[ ! -x "$BIN_DIR/jq" || ! -x "$BIN_DIR/rg" ]]; then
          log "marker set but bins missing — repairing $profile"
        else
          log "profile $profile already installed (marker) — ensuring PATH"
          ensure_path_env
          return 0
        fi
        ;;
      *)
        log "profile $profile already installed (marker) — ensuring PATH"
        ensure_path_env
        return 0
        ;;
    esac
  fi
  log "profile: $profile"
  case "$profile" in
    cli-min)
      install_tool jq
      install_tool rg
      ;;
    cli-dev)
      install_tool jq
      install_tool rg
      install_tool fd
      install_tool unzip
      install_tool file
      ;;
    jp-text)
      install_tool nkf
      ;;
    data)
      install_tool duckdb-py
      install_tool sqlite3
      ;;
    docs-extra)
      install_tool pandoc
      install_tool poppler-utils
      install_tool qpdf
      ;;
    ocr)
      install_tool tesseract-ocr
      install_tool tesseract-ocr-jpn
      ;;
    media)
      install_tool ffmpeg
      install_tool imagemagick
      ;;
    *)
      die "unknown profile: $profile (cli-min|cli-dev|jp-text|data|docs-extra|ocr|media)"
      ;;
  esac
  mark "$key"
  ensure_path_env
  log "profile $profile done"
}

usage() {
  cat <<'U'
Usage: bootstrap.sh <profile> [profile...]

Profiles:
  cli-min     jq + rg          (JSON pipe, workspace search)
  cli-dev     cli-min + fd + unzip + file
  jp-text     nkf
  data        duckdb (python) + sqlite3
  docs-extra  pandoc, poppler-utils, qpdf
  ocr         tesseract + jpn
  media       ffmpeg, imagemagick   (heavy — explicit only)

After run:
  source /workspace/.tools/env
U
}

main() {
  if [[ $# -lt 1 ]]; then
    usage
    exit 0
  fi
  if [[ "$1" == "-h" || "$1" == "--help" ]]; then
    usage
    exit 0
  fi
  if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
    log "warning: not root; apt profiles may fail. static bins still go to $BIN_DIR"
  fi
  for p in "$@"; do
    run_profile "$p"
  done
  ensure_path_env
  log "OK. source $ENV_FILE"
  log "markers: $(tr '\n' ' ' < "$MARKER_FILE")"
}

main "$@"
